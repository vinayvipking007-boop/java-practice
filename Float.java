public class Float {
    public static float add (float a, float b){
        return a + b;
    }
    public static void main(String[] args){
        float a =7;
        float b=4;
        System.out.println("add = "+(a+b));
        System.out.println("substract = "+(a-b));
        System.out.println("multiply = "+(a*b));
        System.out.println("divide = "+(a%b));
    }
    
}
